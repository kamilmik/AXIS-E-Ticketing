    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String nama = txtNama.getText().trim();
        String email = txtEmail.getText().trim();
        String pass = new String(txtPassword.getPassword());
        String telp = txtTelepon.getText().trim();
        String nik = txtNik.getText().trim();

        String result = authController.registerPenumpang(nama, email, pass, telp, nik);
        if (result.equals("SUCCESS")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Akun berhasil dibuat! Silakan login.");
            new LoginView().setVisible(true);
            this.dispose();
        } else if (result.equals("EXIST")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Akun dengan Email atau NIK tersebut sudah ada! Mengarahkan ke Menu Login.", "Info", javax.swing.JOptionPane.WARNING_MESSAGE);
            new LoginView().setVisible(true);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, result, "Validasi Gagal", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

