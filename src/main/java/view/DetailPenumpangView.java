    private void setupEvents() {
        for (java.awt.event.ActionListener al : btnSimpanPenumpang.getActionListeners()) btnSimpanPenumpang.removeActionListener(al);

        btnSimpanPenumpang.addActionListener(e -> {
            String nama = txtNamaPenumpang.getText().trim();
            String telp = txtNoTelepon.getText().trim();
            String nik = txtNikPaspor.getText().trim();

            String res = controller.tambahDataPenumpang(nik, nama, telp);
            if (!res.equals("SUCCESS")) {
                JOptionPane.showMessageDialog(this, res, "Validasi Input", JOptionPane.ERROR_MESSAGE);
                return;
            }

            if (controller.getSisaFormPenumpang() > 0) {
                JOptionPane.showMessageDialog(this, "Data disimpan! masukkan detail penumpang berikutnya.");
                txtNamaPenumpang.setText("");
                txtNoTelepon.setText("");
                txtNikPaspor.setText("");
                perbaruiJudulCounter();
            } else {
                new ReviewPemesananView(controller).setVisible(true);
                this.dispose();
            }
        });
    }
