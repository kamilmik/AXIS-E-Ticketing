    private void rakitTampilan() {
        getContentPane().removeAll();
        getContentPane().setLayout(new BorderLayout(0, 20));
        getContentPane().setBackground(new Color(244, 246, 245));

        JPanel pnlHeader = new JPanel(new BorderLayout());
        pnlHeader.setBackground(new Color(7, 59, 39));
        pnlHeader.setPreferredSize(new Dimension(1200, 110));
        pnlHeader.setBorder(BorderFactory.createEmptyBorder(25, 70, 25, 70));

        JLabel lblTitle = new JLabel("Pilih Jadwal Kereta Antarkota Tersedia");
        lblTitle.setFont(new Font("Verdana", Font.BOLD, 26));
        lblTitle.setForeground(Color.WHITE);
        pnlHeader.add(lblTitle, BorderLayout.WEST);

        JPanel pnlBody = new JPanel(new BorderLayout(0, 20));
        pnlBody.setOpaque(false);
        pnlBody.setBorder(BorderFactory.createEmptyBorder(20, 70, 40, 70));

        modelJadwal = new DefaultTableModel(
            new String[]{"ID Jadwal", "Nama Kereta", "Waktu Berangkat", "Waktu Tiba", "Harga Dasar"}, 0
        ) {
            @Override public boolean isCellEditable(int r, int c) { return false; }
        };
        tblJadwal.setModel(modelJadwal);
        tblJadwal.setRowHeight(36);
        tblJadwal.setFont(new Font("Verdana", Font.PLAIN, 14));
        tblJadwal.setSelectionBackground(new Color(0, 108, 59));
        tblJadwal.setSelectionForeground(Color.WHITE);
        tblJadwal.getTableHeader().setFont(new Font("Verdana", Font.BOLD, 14));

        JPanel pnlBottom = new JPanel(new FlowLayout(FlowLayout.RIGHT, 15, 0));
        pnlBottom.setOpaque(false);

        btnKembali.setText("Kembali");
        btnKembali.setFont(new Font("Verdana", Font.BOLD, 14));
        btnKembali.setPreferredSize(new Dimension(160, 48));
        btnKembali.setBackground(new Color(220, 225, 222));

        btnPilihJadwal.setText("Pilih Layanan Kereta");
        btnPilihJadwal.setFont(new Font("Verdana", Font.BOLD, 14));
        btnPilihJadwal.setPreferredSize(new Dimension(240, 48));
        btnPilihJadwal.setBackground(new Color(0, 108, 59));
        btnPilihJadwal.setForeground(Color.WHITE);

        pnlBottom.add(btnKembali);
        pnlBottom.add(btnPilihJadwal);

        pnlBody.add(new JScrollPane(tblJadwal), BorderLayout.CENTER);
        pnlBody.add(pnlBottom, BorderLayout.SOUTH);

        getContentPane().add(pnlHeader, BorderLayout.NORTH);
        getContentPane().add(pnlBody, BorderLayout.CENTER);
        revalidate();
        repaint();
    }

    private void setupEvents() {
        for (java.awt.event.ActionListener al : btnPilihJadwal.getActionListeners()) btnPilihJadwal.removeActionListener(al);
        for (java.awt.event.ActionListener al : btnKembali.getActionListeners()) btnKembali.removeActionListener(al);

        btnPilihJadwal.addActionListener(e -> {
            int row = tblJadwal.getSelectedRow();
            if (row == -1) {
                JOptionPane.showMessageDialog(this, "Silakan pilih salah satu jadwal kereta pada tabel!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                return;
            }
            int idJadwal = Integer.parseInt(tblJadwal.getValueAt(row, 0).toString());
            controller.setJadwalTerpilih(idJadwal);

            new DetailPenumpangView(controller).setVisible(true);
            this.dispose();
        });

        btnKembali.addActionListener(e -> {
            new MenuUtamaView().setVisible(true);
            this.dispose();
        });
    }

