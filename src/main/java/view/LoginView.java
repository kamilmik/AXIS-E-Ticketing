    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String email = txtEmail.getText().trim();
        String pass = new String(txtPassword.getPassword());

        String result = authController.loginPenumpang(email, pass);
        if (result.equals("SUCCESS")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Berhasil Login! Selamat datang, " 
                    + controller.SessionManager.getCurrentPenumpang().getNamaLengkap());
                    new MenuUtamaView().setVisible(true);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, result, "Login Gagal", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

