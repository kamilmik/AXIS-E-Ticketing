    private void btnLoginAdminActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginAdminActionPerformed
        String kode = txtKodeKaryawan.getText().trim();
        String pass = new String(txtPassword.getPassword());

        String result = authController.loginAdmin(kode, pass);
        if (result.equals("SUCCESS")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Login Admin Berhasil! Level Akses: " 
                    + controller.SessionManager.getCurrentAdmin().getLevelAkses());
            new DashboardAdminView().setVisible(true);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, result, "Akses Ditolak", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginAdminActionPerformed

